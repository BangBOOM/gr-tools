import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
const root=fileURLToPath(new URL('../',import.meta.url));
for(const [cmd,args] of [
  ['cargo',['build','--locked','--manifest-path',`${root}rust/Cargo.toml`,'--release','--target','wasm32-unknown-unknown']],
  ['wasm-bindgen',[`${root}rust/target/wasm32-unknown-unknown/release/gr_firmware_fit.wasm`,'--target','web','--out-dir',`${root}wasm`,'--out-name','gr_firmware_fit']],
]) {const p=spawnSync(cmd,args,{stdio:'inherit'});if(p.status!==0)process.exit(p.status??1);}

const hash=(...paths)=>{const h=createHash('sha256');for(const path of paths)h.update(readFileSync(path));return h.digest('hex');};
writeFileSync(`${root}wasm/pin.ts`, `// Generated by scripts/build-wasm.mjs; never edit manually.\nexport const FIT_WASM_SHA256 = '${hash(`${root}wasm/gr_firmware_fit_bg.wasm`)}';\nexport const FIT_RUST_SOURCE_SHA256 = '${hash(`${root}rust/src/lib.rs`,`${root}rust/src/native_gamma.rs`)}';\nexport const FIT_EVALUATOR_SOURCE_SHA256 = '${hash(`${root}src/index.ts`,`${root}../color-engine/camera.ts`)}';\n`);
